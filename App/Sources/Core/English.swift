    static func translate(_ message: String) -> String? {
        if let exact = table[message] { return exact }
        let range = NSRange(message.startIndex ..< message.endIndex, in: message)
        for (expression, template) in patterns where expression.firstMatch(in: message, range: range) != nil {
            return expression.stringByReplacingMatches(in: message, range: range, withTemplate: template)
        }
        return nil
    }
